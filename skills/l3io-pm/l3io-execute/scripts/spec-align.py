# -- the spec-sync lease ---------------------------------------------------------------------- #
# Parallel epic closures share one working tree: without a lease two agents can edit one
# architecture doc at once, or one commits the other's half-made edit. It is a lease, not a
# flock, because it must survive an agent's many turns; the flock only guards the file's
# read-decide-write. The `.lock` name puts it under pm-status's `*.lock` rule in
# the state root's .gitignore, which pm-status writes on its first locked write there.

LEASE_NAME = "spec-sync.lock"


class LeaseHeld(Exception):
    pass


def _now():
    from datetime import datetime
    return datetime.now(UTC)


def _iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_iso(s):
    from datetime import datetime
    try:
        return datetime.strptime(str(s), "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC)
    except ValueError:
        return None


def _lease_path(ctx):
    ctx.need("state")
    os.makedirs(ctx.state_root, exist_ok=True)
    return os.path.join(ctx.state_root, LEASE_NAME)


def _lease_read(fh):
    fh.seek(0)
    raw = fh.read().strip()
    if not raw:
        return None
    try:
        cur = json.loads(raw)
    except ValueError:
        sys.stderr.write(f"WARN {LEASE_NAME} is not JSON; treating the lease as free\n")
        return None
    return cur if isinstance(cur, dict) else None


def _lease_write(fh, value):
    fh.seek(0)
    fh.truncate()
    if value is not None:
        fh.write(json.dumps(value))
    fh.flush()
    os.fsync(fh.fileno())


def _lease_try(path, owner, ttl_minutes):
    import fcntl
    from datetime import timedelta
    with open(path, "a+", encoding="utf-8") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            cur, now = _lease_read(fh), _now()
            if cur and cur.get("owner") != owner:
                expires = _parse_iso(cur.get("expires_at"))
                if expires is not None and expires > now:
                    raise LeaseHeld(cur)
                sys.stderr.write(f"WARN spec-sync lease held by {cur.get('owner')} expired at "
                                 f"{cur.get('expires_at')}; taking it over\n")
            new = {"owner": owner, "acquired_at": _iso(now),
                   "expires_at": _iso(now + timedelta(minutes=ttl_minutes))}
            _lease_write(fh, new)
            return new
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


def cmd_lease(ctx, a):
    import fcntl
    owner = epic_key(a.owner)
    if owner is None:
        raise SAError(2, f"--owner {a.owner!r} is not an epic key")
    path = _lease_path(ctx)
    if a.lease_cmd == "acquire":
        from tenacity import retry, retry_if_exception_type, stop_after_delay, wait_fixed

        @retry(retry=retry_if_exception_type(LeaseHeld), reraise=True,
               stop=stop_after_delay(a.wait_minutes * 60), wait=wait_fixed(a.poll_seconds))
        def attempt():
            return _lease_try(path, owner, a.ttl_minutes)

        try:
            new = attempt()
        except LeaseHeld as e:
            cur = e.args[0]
            sys.stderr.write(f"spec-sync lease held by {cur.get('owner')} until "
                             f"{cur.get('expires_at')}\n")
            return 5
        print(f"OK lease acquired by {owner} until {new['expires_at']}")
        return 0
    with open(path, "a+", encoding="utf-8") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            cur = _lease_read(fh)
            if not cur:
                print("OK lease already free")
                return 0
            if cur.get("owner") != owner:
                raise SAError(2, f"the lease is held by {cur.get('owner')}, not {owner}")
            _lease_write(fh, None)
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)
    print(f"OK lease released by {owner}")
    return 0


# -- git and pm-status helpers ------------------------------------------------------------- #

def _pm(ctx, *args):
    ctx.need("pm")
    return subprocess.run([sys.executable, ctx.pm_status, *args], capture_output=True, check=False, text=True)


class IndexLocked(Exception):
    pass


def _git(ctx, *args, check=True):
    try:
        r = subprocess.run(["git", "-C", ctx.project, *args], capture_output=True, check=False, text=True)
    except OSError as e:
        raise SAError(2, f"git is not available: {e}")
    if check and r.returncode != 0:
        raise SAError(2, f"git {' '.join(args)} failed: {(r.stderr or r.stdout).strip()}")
    return r


def git_commit(ctx, message, paths):
    """`git commit -s --only -- paths`: exactly those paths, even in a checkout other agents
    share. A held index.lock is retried with backoff (tenacity), then refused."""
    from tenacity import retry, retry_if_exception_type, stop_after_attempt, wait_exponential

    @retry(retry=retry_if_exception_type(IndexLocked), reraise=True,
           stop=stop_after_attempt(5), wait=wait_exponential(multiplier=0.2, max=2))
    def attempt():
        r = _git(ctx, "commit", "-s", "--only", "-m", message, "--", *paths, check=False)
        if r.returncode != 0:
            err = (r.stderr or r.stdout).strip()
            if "index.lock" in err:
                raise IndexLocked(err)
            raise SAError(2, f"git commit failed: {err}")

    try:
        attempt()
    except IndexLocked as e:
        raise SAError(2, f"the git index stayed locked after 5 attempts: {e}")
    return _git(ctx, "rev-parse", "HEAD").stdout.strip()


# -- migrate-adrs: the old per-epic home -> docs/adr (ADR-0005) ------------------------------- #

def _migration_plan(ctx):
    ctx.need("impl", "state")
    docs_dir = os.path.join(ctx.project, "docs", "adr")
    docs_by_num = {}
    if os.path.isdir(docs_dir):
        docs_by_num = {int(m.group(1)): m.group(2)
                       for m in map(DOC_ADR_RE.match, os.listdir(docs_dir)) if m}
    docs_nums = set(docs_by_num)
    moves, taken = [], set(docs_nums)
    for p in sorted(glob.glob(os.path.join(ctx.impl, "epic-*", "arch", "adr-*.md"))):
        m = LEGACY_ADR_RE.match(os.path.basename(p))
        em = re.search(r"epic-(\d{3})", os.path.basename(os.path.dirname(os.path.dirname(p))))
        if not (m and em):
            continue
        n, slug = int(m.group(1)), m.group(2)
        # A same-number AND same-slug file in docs/adr is not a competing decision -- it IS
        # this decision, already migrated, and the epic copy is a leftover (often a stale
        # pre-supersession snapshot). Renumbering it mints a duplicate ADR under a fresh
        # number and rewrites the epic's artifacts to cite the invented one. Observed on a
        # real project: all 14 legacy ADRs were duplicates, so every single one would have
        # been minted as new. Only a DIFFERENT slug is a genuine collision.
        dup = docs_by_num.get(n) == slug
        moves.append({"from": ctx.rel(p), "number": n, "slug": slug, "epic": f"E{em.group(1)}",
                      "duplicate": dup,
                      "collision": (n in taken) and not dup,
                      "to": None if n in taken else f"docs/adr/{n:04d}-{slug}.md"})
        taken.add(n)
    reg = load_yaml(os.path.join(ctx.state_root, "adr-register.yaml")) or {}
    try:
        nxt = int(reg.get("next", 1))
    except (TypeError, ValueError):
        nxt = 1
    hi = max([*docs_nums, *(mv["number"] for mv in moves)], default=0)
    return {"moves": moves,
            "duplicates": [mv for mv in moves if mv["duplicate"]],
            "actionable": [mv for mv in moves if not mv["duplicate"]],
            "register": {"next": nxt, "highest_on_disk": hi, "lagging": hi > 0 and nxt <= hi},
            "rewritten": [], "rewritten_uncommitted": [], "review": [], "commit": None}


def _add_epic_line(text, ek):
    if re.search(r"^-\s+\*\*Epic:\*\*", text, re.MULTILINE):
        return text
    text2, n = re.subn(r"^(-\s+\*\*Status:\*\*.*)$", rf"\1\n- **Epic:** {ek}", text,
                       count=1, flags=re.MULTILINE)
    return text2 if n else re.sub(r"^(#[^\n]*\n)", rf"\1\n- **Epic:** {ek}\n", text, count=1)


def cmd_migrate_adrs(ctx, a):
    plan = _migration_plan(ctx)
    # A duplicate is reported, never moved: nothing for --apply to do about it. When every
    # move is a duplicate there is no work at all, and proceeding would open a git
    # transaction that commits nothing.
    if a.plan or not plan["actionable"]:
        print(json.dumps(plan, indent=2))
        return 0
    if _git(ctx, "rev-parse", "--is-inside-work-tree", check=False).stdout.strip() != "true":
        raise SAError(2, "migrate-adrs --apply needs a git work tree")
    docs_dir = os.path.join(ctx.project, "docs", "adr")
    md_files = sorted(set(glob.glob(os.path.join(ctx.impl, "**", "*.md"), recursive=True)))
    # Pre-flight: refuse if any path this run would touch already has uncommitted changes.
    # A previous --apply that stopped partway (adr-reserve, git mv, or the process itself
    # failing) leaves the tree mutated with nothing committed; a rerun's _migration_plan no
    # longer sees the already-moved files (they left epic-*/arch/), so it would quietly plan
    # less work over stray state instead of surfacing it. This is what stops that compounding.
    # The loop below can rewrite a *.md file in ANY epic (an exact path reference to the
    # moved ADR, or -- when renumbering -- a bare ADR-NNNN mention inside the moving ADR's own
    # epic tree), not only files under the source epic-*/arch/ or its own tree, so those
    # matching files are checked individually rather than assumed clean.
    check_paths = {ctx.rel(docs_dir)}
    for mv in plan["actionable"]:
        nnn, old, slug = mv["epic"][1:], mv["number"], mv["slug"]
        check_paths.add(os.path.dirname(mv["from"]))                       # its epic-*/arch/
        check_paths.add(f"{ctx.rel(ctx.impl)}/epic-{nnn}")                  # its own epic tree
        path_re = re.compile(rf"[\w./-]*epic-{nnn}/arch/adr-{old:04d}-{re.escape(slug)}\.md")
        for f in md_files:
            if os.path.isfile(f) and path_re.search(read_text(f)):
                check_paths.add(ctx.rel(f))                                # any file naming it
        if mv["collision"]:
            num_re = re.compile(rf"\bADR-{old:04d}\b")
            epic_tree = os.path.join(ctx.impl, f"epic-{nnn}")
            for f in md_files:
                if (os.path.isfile(f) and _under(f, epic_tree)
                        and num_re.search(read_text(f))):
                    check_paths.add(ctx.rel(f))                            # renumber target
    dirty = _git(ctx, "status", "--porcelain", "--", *sorted(check_paths), check=False).stdout
    if dirty.strip():
        raise SAError(2, "migrate-adrs --apply refuses: uncommitted changes already sit under "
                         f"{', '.join(sorted(check_paths))} -- a previous run may have stopped "
                         f"midway. Inspect and commit or revert those paths by hand (never a "
                         f"repo-wide discard; other agents share this checkout), then retry:\n"
                         f"{dirty}")
    os.makedirs(docs_dir, exist_ok=True)
    other_docs = sorted(glob.glob(os.path.join(ctx.project, "docs", "**", "*.md"),
                                  recursive=True))
    commit_paths, rewritten, touched = [], set(), []
    try:
        for mv in plan["actionable"]:
            old, nnn = mv["number"], mv["epic"][1:]
            new = old
            if mv["collision"]:
                r = _pm(ctx, "adr-reserve", "--state-root", ctx.state_root, "--epic", mv["epic"],
                        "--slug", f"migrate-{mv['slug']}", "--adr-dir", docs_dir)
                if r.returncode != 0 or not r.stdout.split():
                    raise SAError(2, f"adr-reserve failed: {(r.stderr or r.stdout).strip()}")
                new = int(r.stdout.split()[0])
                mv["renumbered_to"] = new
                mv["to"] = f"docs/adr/{new:04d}-{mv['slug']}.md"
            tracked = _git(ctx, "ls-files", "--error-unmatch", "--", mv["from"],
                           check=False).returncode == 0
            if tracked:
                _git(ctx, "mv", "--", mv["from"], mv["to"])
                commit_paths += [mv["from"], mv["to"]]
            else:
                os.replace(ctx.abs(mv["from"]), ctx.abs(mv["to"]))
                _git(ctx, "add", "--", mv["to"])
                commit_paths.append(mv["to"])
            touched.append(mv["to"])
            body = read_text(ctx.abs(mv["to"]))
            if new != old:
                body = re.sub(rf"\bADR-{old:04d}\b", f"ADR-{new:04d}", body)
            atomic_write(ctx.abs(mv["to"]), _add_epic_line(body, mv["epic"]))
            path_re = re.compile(
                rf"[\w./-]*epic-{nnn}/arch/adr-{old:04d}-{re.escape(mv['slug'])}\.md")
            num_re = re.compile(rf"\bADR-{old:04d}\b")
            epic_tree = os.path.join(ctx.impl, f"epic-{nnn}")
            for f in md_files:
                if not os.path.isfile(f):
                    continue
                text = read_text(f)
                inside = _under(f, epic_tree)
                if new != old and not inside:
                    for i, line in enumerate(text.splitlines(), 1):
                        if num_re.search(line):
                            plan["review"].append({"file": ctx.rel(f), "line": i,
                                                   "text": line.strip()})
                text2 = path_re.sub(mv["to"], text)
                if new != old and inside:
                    text2 = num_re.sub(f"ADR-{new:04d}", text2)
                if text2 != text:
                    atomic_write(f, text2)
                    rel = ctx.rel(f)
                    rewritten.add(rel)
                    touched.append(rel)
            if new != old:
                for f in other_docs:
                    if re.match(rf"{old:04d}-", os.path.basename(f)) and _under(f, docs_dir):
                        continue                      # that number's rightful owner
                    for i, line in enumerate(read_text(f).splitlines(), 1):
                        if num_re.search(line):
                            plan["review"].append({"file": ctx.rel(f), "line": i,
                                                   "text": line.strip()})
        rewritten_committed, rewritten_uncommitted = [], []
        for rel in sorted(rewritten):
            if _git(ctx, "ls-files", "--error-unmatch", "--", rel, check=False).returncode == 0:
                commit_paths.append(rel)
                rewritten_committed.append(rel)
            else:
                sys.stderr.write(f"WARN {rel} was rewritten but is not tracked; not committed\n")
                rewritten_uncommitted.append(rel)
        plan["rewritten"] = rewritten_committed
        plan["rewritten_uncommitted"] = rewritten_uncommitted
        plan["commit"] = git_commit(ctx, "docs(adr): migrate epic ADRs to docs/adr",
                                    list(dict.fromkeys(commit_paths)))
    except Exception as e:
        # No automatic rollback: undoing renames and text substitutions across a repo is more
        # dangerous than the problem, and the pre-flight refusal above is what stops a rerun
        # from compounding this. Fail loud instead, naming exactly what this run already
        # touched so a person can inspect and commit or revert those paths by hand. The commit
        # itself is inside this guard too: a commit-time failure (a rejecting hook, or the
        # index lock exhausted after retries) happens once every file is already moved and
        # rewritten -- exactly the state this message exists to describe.
        code = e.code if isinstance(e, SAError) else 2
        detail = ", ".join(dict.fromkeys(touched)) or "(nothing written yet)"
        raise SAError(code, f"{e} -- migrate-adrs --apply failed partway; paths already moved "
                             f"or rewritten in this run: {detail}. Inspect them and either "
                             f"commit or revert exactly those paths by hand -- never a "
                             f"repo-wide discard; other agents share this checkout.") from e
    print(json.dumps(plan, indent=2))
    return 0


