INDEX_FORMAT = 1
INDEX_REL = os.path.join("spec", "spec-index.md")
INDEX_MAX_LEVEL = 3
SUMMARY_CHARS = 100
SIZE_WARN_BYTES = 16384
HEADER_TITLE = "# Spec index — generated by spec-align.py; do not edit"
DIGEST_RE = re.compile(r"^# inputs-sha256: ([0-9a-f]{64})\b")
SPEC_PATHS_RE = re.compile(r"^# spec-paths: (.*)$")

# Spec kinds in precedence order: a name matching several kinds takes the first.
KINDS = (
    ("architecture", ("*architecture*", "*arch-spec*", "*system-design*", "*tech-design*")),
    ("ux", ("*ux-spec*", "*ux-design*", "*wireframe*", "*mockup*", "*ui-spec*")),
    ("prd", ("*requirements*", "*prd*", "*brief*", "*spec*")),
    ("epics", ("*epics*",)),
)
KIND_ORDER = {k: i for i, (k, _) in enumerate(KINDS)}


class SAError(Exception):
    """A refusal: `code` is the exit status; the message goes to stderr."""

    def __init__(self, code, msg):
        super().__init__(msg)
        self.code = code


class Ctx:
    """The paths every subcommand resolves against, from the global flags."""

    def __init__(self, a):
        self.project = os.path.abspath(a.project_root)
        self.planning = os.path.abspath(a.planning_root) if a.planning_root else None
        self.impl = os.path.abspath(a.impl_root) if a.impl_root else None
        self.state_root = (os.path.abspath(a.state_root) if a.state_root
                           else (os.path.join(self.impl, "state") if self.impl else None))
        self.pm_status = a.pm_status or None
        self.spec_paths_arg = None
        if a.spec_paths is not None:
            if not a.spec_paths.strip():
                value = []
            else:
                try:
                    value = json.loads(a.spec_paths)
                except ValueError as e:
                    raise SAError(2, f"--spec-paths is not JSON: {e}")
            if not isinstance(value, list) or not all(isinstance(x, str) for x in value):
                raise SAError(2, "--spec-paths must be a JSON list of strings")
            self.spec_paths_arg = value

    def need(self, *what):
        flags = {"impl": ("--impl-root", self.impl), "state": ("--state-root", self.state_root),
                 "pm": ("--pm-status", self.pm_status)}
        missing = [flags[w][0] for w in what if not flags[w][1]]
        if missing:
            raise SAError(2, f"this subcommand needs {', '.join(missing)}")

    def rel(self, p):
        return os.path.relpath(os.path.abspath(p), self.project).replace(os.sep, "/")

    def abs(self, p):
        return p if os.path.isabs(p) else os.path.join(self.project, p)

    def index_path(self):
        self.need("impl")
        return os.path.join(self.impl, INDEX_REL)


def _under(path, root):
    path, root = os.path.abspath(path), os.path.abspath(root)
    return path == root or path.startswith(root + os.sep)


def read_text(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def atomic_write(path, text):
    """Write via a sibling temp file + os.replace, so a reader never sees half a file."""
    d = os.path.dirname(os.path.abspath(path))
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".spec-align-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


# -- markdown ------------------------------------------------------------------------------ #

_MD = None


def md():
    """One parser for every read. Anchors are computed over every heading level, so duplicate
    suffixes (-1, -2) count the same headings GitHub does; the index lists H1-H3 only."""
    global _MD
    if _MD is None:
        try:
            from markdown_it import MarkdownIt
            from mdit_py_plugins.anchors import anchors_plugin
        except ImportError as exc:
            # This script's dependencies come from its PEP-723 header, which only `uv run`
            # reads. Reached under a bare interpreter, the lazy import dies with a traceback
            # naming a package nobody asked for -- so say what is actually wrong instead.
            raise SAError(2, f"spec-align.py needs its PEP-723 dependencies ({exc.name}). "
                             f"Run it under uv, not a bare interpreter:\n"
                             f"  uv run {os.path.basename(__file__)} <subcommand> ...") from exc
        _MD = MarkdownIt("commonmark").enable("table").use(anchors_plugin,
                                                           min_level=1, max_level=6)
    return _MD


_FM_CLOSE = re.compile(r"^(?:---|\.\.\.)\s*$")


def parse_md(text):
    """`md().parse`, with a leading YAML frontmatter block blanked out first.

    WHY: in Markdown, a line followed by `---` is a SETEXT h2. So frontmatter

        ---
        status: draft
        ---

    parses as an h2 titled "status: draft", and every heading reader here picks it up --
    the index grew a phantom `#status-draft` section pointing at the YAML. Pre-existing,
    but BMad 6.12.1 started writing that exact frontmatter into `epics.md`, which put it
    in front of every project that runs the planning skill.

    BLANKED, NOT REMOVED. Every caller reports 1-based line numbers straight out of
    `token.map`, so deleting the lines would silently shift every range in the document.
    Replacing them with empty lines keeps the arithmetic identical.

    Only a block at the very TOP counts. A `---` later in the file is a thematic break and
    the line above it is a legitimate setext heading -- a test pins that, because narrowing
    the rule to "first line" is what keeps this from eating real headings.
    """
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip("\r\n") != "---":
        return md().parse(text)
    for i in range(1, len(lines)):
        if _FM_CLOSE.match(lines[i].rstrip("\r\n")):
            blanked = ["\n"] * (i + 1) + lines[i + 1:]
            return md().parse("".join(blanked))
    # No closing delimiter: not frontmatter, just a document opening with a rule.
    return md().parse(text)


class Section:
    __slots__ = ("anchor", "end", "level", "start", "summary", "title")

    def __init__(self, level, title, anchor, start, end, summary):
        self.level, self.title, self.anchor = level, title, anchor
        self.start, self.end, self.summary = start, end, summary


def first_sentence(text):
    s = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(?:\s|$)", s)
    if m:
        s = m.group(1)
    return s if len(s) <= SUMMARY_CHARS else s[:SUMMARY_CHARS - 1].rstrip() + "…"


def parse_sections(text):
    """Every heading as a Section. A section runs from its heading line to the line before
    the next heading of the same or a higher level (1-based, inclusive)."""
    tokens = parse_md(text)
    nlines = len(text.splitlines())
    heads = [(i, int(t.tag[1:]), t.attrs.get("id"), t.map[0], tokens[i + 1].content.strip())
             for i, t in enumerate(tokens) if t.type == "heading_open"]
    out = []
    for n, (i, level, anchor, line0, title) in enumerate(heads):
        end = nlines
        for _, level2, _, line2, _ in heads[n + 1:]:
            if level2 <= level:
                end = line2
                break
        stop = heads[n + 1][0] if n + 1 < len(heads) else len(tokens)
        summary = ""
        for j in range(i + 3, stop):
            if (tokens[j].type == "paragraph_open" and j + 1 < stop
                    and tokens[j + 1].type == "inline"):
                summary = first_sentence(tokens[j + 1].content)
                break
        out.append(Section(level, title, anchor, line0 + 1, max(end, line0 + 1), summary))
    return out


# -- discovery and the catalog -------------------------------------------------------------- #

def kind_of(name):
    low = name.lower()
    for kind, patterns in KINDS:
        if any(fnmatch.fnmatchcase(low, p) for p in patterns):
            return kind
    return None


def _kind_for_path(p):
    """A file takes its own name's kind, else its directory's (a sharded doc's section)."""
    return kind_of(os.path.basename(p)) or kind_of(os.path.basename(os.path.dirname(p)))


def recorded_spec_paths(ctx):
    """The spec-paths list the current index was built with, or None."""
    if not ctx.impl:
        return None
    p = os.path.join(ctx.impl, INDEX_REL)
    if not os.path.isfile(p):
        return None
    with open(p, encoding="utf-8") as fh:
        for n, line in enumerate(fh):
            if n > 4:
                break
            m = SPEC_PATHS_RE.match(line.rstrip("\n"))
            if m:
                try:
                    value = json.loads(m.group(1))
                except ValueError:
                    return None
                return value if isinstance(value, list) else None
    return None


def effective_spec_paths(ctx):
    """--spec-paths when given; else the list the index records (so doctor, which cannot read
    pm-execute's customize.toml, checks the same spec set); else [] (discover)."""
    if ctx.spec_paths_arg is not None:
        return list(ctx.spec_paths_arg)
    rec = recorded_spec_paths(ctx)
    return rec if rec is not None else []


def discover(ctx):
    """[(project-relative path, kind)], sorted. spec_paths replaces discovery entirely."""
    found = {}
    skip = os.path.join(ctx.impl, "spec") if ctx.impl else None      # never index the index
    patterns = effective_spec_paths(ctx)
    if patterns:
        for pat in patterns:
            for hit in glob.glob(os.path.join(ctx.project, pat), recursive=True):
                if os.path.isfile(hit) and hit.endswith(".md") and not (skip and _under(hit, skip)):
                    found[ctx.rel(hit)] = _kind_for_path(hit) or "other"
    elif ctx.planning and os.path.isdir(ctx.planning):
        for dirpath, dirnames, filenames in os.walk(ctx.planning):
            if skip and _under(dirpath, skip):
                dirnames[:] = []
                continue
            keep = []
            for d in sorted(dirnames):
                full = os.path.join(dirpath, d)
                kind = kind_of(d)
                if skip and _under(full, skip):
                    continue
                if kind and os.path.isfile(os.path.join(full, "index.md")):
                    for sub_dir, _, sub_files in os.walk(full):
                        for f in sub_files:
                            if f.endswith(".md"):
                                found[ctx.rel(os.path.join(sub_dir, f))] = kind
                else:
                    keep.append(d)
            dirnames[:] = keep
            for f in filenames:
                if f.endswith(".md"):
                    kind = kind_of(f)
                    if kind:
                        found[ctx.rel(os.path.join(dirpath, f))] = kind
    return sorted(found.items())


def catalog_entry(ctx, rel, kind):
    """{"kind", "sections", "anchors", "error", "sha"} for one spec file."""
    e = {"kind": kind, "sections": [], "anchors": {}, "error": None, "sha": ""}
    try:
        with open(ctx.abs(rel), "rb") as fh:
            raw = fh.read()
    except OSError as exc:
        e["error"], e["sha"] = f"unreadable: {exc.strerror or exc}", "unreadable"
    else:
        e["sha"] = hashlib.sha256(raw).hexdigest()
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            e["error"] = "not UTF-8"
        else:
            e["sections"] = parse_sections(text)
            e["anchors"] = {s.anchor: s for s in e["sections"]}
    return e


def load_catalog(ctx):
    """{rel: catalog_entry} for every discovered spec."""
    return {rel: catalog_entry(ctx, rel, kind) for rel, kind in discover(ctx)}


def inputs_hash(ctx, cat):
    h = hashlib.sha256()
    h.update(f"format={INDEX_FORMAT}\n"
             f"spec-paths={json.dumps(effective_spec_paths(ctx))}\n".encode())
    for rel in sorted(cat):
        h.update(f"{rel}\0{cat[rel]['sha']}\n".encode())
    return h.hexdigest()


def render_index(ctx, cat, digest):
    body, skipped, n_specs, n_sections = [], [], 0, 0
    for rel in sorted(cat, key=lambda r: (KIND_ORDER.get(cat[r]["kind"], 99), r)):
        e = cat[rel]
        if e["error"]:
            skipped.append(f"- skipped: {rel} ({e['error']})")
            continue
        n_specs += 1
        body.append(f"## {e['kind']} · {rel}")
        for s in e["sections"]:
            if s.level > INDEX_MAX_LEVEL:
                continue
            n_sections += 1
            summary = f": {s.summary}" if s.summary else ""
            body.append(f"- {rel}#{s.anchor} — {s.title}{summary} (L{s.start}–{s.end})")
    if skipped:
        body += ["## skipped", *skipped]
    if not cat:
        body.append("no spec docs found")
    text = "\n".join(body) + "\n"
    nbytes = len(text.encode("utf-8"))            # R12: the body below the header
    header = (f"{HEADER_TITLE}\n"
              f"# inputs-sha256: {digest}  ·  bytes: {nbytes:,}  ·  specs: {n_specs}  ·  "
              f"sections: {n_sections}\n"
              f"# spec-paths: {json.dumps(effective_spec_paths(ctx))}\n")
    return header + text, nbytes, n_specs, n_sections


def index_digest(path):
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh):
            if n > 4:
                break
            m = DIGEST_RE.match(line)
            if m:
                return m.group(1)
    return None


def cmd_build(ctx, a):
    path = ctx.index_path()
    cat = load_catalog(ctx)
    digest = inputs_hash(ctx, cat)
    fresh = index_digest(path) == digest
    if a.check:
        if fresh:
            print(f"OK build --check: {ctx.rel(path)} is fresh")
            return 0
        print(f"STALE {ctx.rel(path)}: the specs changed since it was built "
              f"(or it does not exist) -- run build")
        return 1
    if a.if_stale and fresh:
        print(f"OK build: {ctx.rel(path)} is fresh; not rewritten")
        return 0
    text, nbytes, n_specs, n_sections = render_index(ctx, cat, digest)
    atomic_write(path, text)
    if nbytes > SIZE_WARN_BYTES:
        sys.stderr.write(f"WARN spec index is {nbytes:,} bytes (> {SIZE_WARN_BYTES:,}); every "
                         f"reviewer reads it -- consider trimming (spec §8)\n")
    print(f"OK build: wrote {ctx.rel(path)} ({n_specs} spec(s), {n_sections} section(s), "
          f"{nbytes:,} bytes)")
    return 0


# -- provenance pointers ---------------------------------------------------------------------- #

# The six technical-AC dimensions, in the order ac-dimensions.md lays them out. check-docs
# check 13 compares this tuple with that layout block; keep it a literal, one name per line.
DIMENSIONS = (
    "Interface contracts",
    "Error and edge case handling",
    "Observability requirements",
    "Security considerations",
    "Testability approach",
    "Existing-library check",
)
TAC_HEADING = "Technical acceptance criteria"
# The two business-AC dimensions, in the order ac-dimensions.md lays them out. check-docs
# check 13 compares this tuple with that layout block; keep it a literal, one name per line.
BUSINESS_DIMENSIONS = (
    "Outcome",
    "Non-goals",
)
BAC_HEADING = "Business acceptance criteria"
# Dimensions exempt from the `Spec:` requirement: a negative scope statement has no spec
# section to resolve against, and demanding `Spec: none — n/a` on every story is noise.
NO_POINTER_DIMENSIONS = frozenset({"Non-goals"})
SPEC_LINE_RE = re.compile(r"^\s*(?:[-*]\s+)?Spec:\s*(.*?)\s*$")
NONE_RE = re.compile(r"^none\s*(?:—|--|-)\s*(\S.*)$", re.IGNORECASE)
PTR_RE = re.compile(r"^([^\s#`]+\.md)#([^\s#`]+)$")
NA_RE = re.compile(r"^\s*N/A\s*(?:—|--|-)\s*\S")


def story_dimensions(text):
    """({section: h2 found}, {section: {casefolded dimension: (h3 line, [(lineno, line), ...])}})
    for the story's `## Business acceptance criteria` ("bac") and `## Technical acceptance
    criteria` ("tac") sections. Dimensions are kept per section, so one placed under the wrong
    h2 satisfies neither gate. Lines inside fenced or indented code are dropped."""
    tokens = parse_md(text)
    lines = text.splitlines()
    fenced = set()
    for t in tokens:
        if t.type in ("fence", "code_block") and t.map:
            fenced.update(range(t.map[0], t.map[1]))
    heads = [(t.map[0], int(t.tag[1:]), tokens[i + 1].content.strip())
             for i, t in enumerate(tokens) if t.type == "heading_open"]
    found, dims = {}, {"bac": {}, "tac": {}}
    for key, heading in (("bac", BAC_HEADING), ("tac", TAC_HEADING)):
        at = next((ln for ln, lvl, title in heads
                   if lvl == 2 and title.casefold() == heading.casefold()), None)
        found[key] = at is not None
        if at is None:
            continue
        end = next((ln for ln, lvl, _ in heads if ln > at and lvl <= 2), len(lines))
        h3 = [(ln, title) for ln, lvl, title in heads if at < ln < end and lvl == 3]
        for n, (ln, title) in enumerate(h3):
            stop = h3[n + 1][0] if n + 1 < len(h3) else end
            body = [(i + 1, lines[i]) for i in range(ln + 1, stop) if i not in fenced]
            dims[key][title.casefold()] = (ln + 1, body)
    return found, dims


def resolve_pointer(cat, value):
    """((path, anchor, Section, kind), None) or (None, why)."""
    m = PTR_RE.match(value.strip().strip("`"))
    if not m:
        return None, f"not a pointer: {value!r} (expected <path>#<anchor>)"
    path, anchor = m.groups()
    e = cat.get(path)
    if e is None:
        return None, f"{path} {getattr(cat, 'missing', 'is not in the spec index')}"
    if e["error"]:
        return None, f"{path} is unreadable ({e['error']})"
    s = e["anchors"].get(anchor)
    if s is None:
        return None, f"{path} has no anchor #{anchor}"
    return (path, anchor, s, e["kind"]), None


def story_pointers(text):
    """[(lineno, dimension, value)] for every Spec: line under a known dimension."""
    _found, dims = story_dimensions(text)
    out = []
    for sect, names in (("tac", DIMENSIONS), ("bac", BUSINESS_DIMENSIONS)):
        for dim in names:
            for n, line in (dims[sect].get(dim.casefold()) or (0, []))[1]:
                m = SPEC_LINE_RE.match(line)
                if m:
                    out.append((n, dim, m.group(1)))
    return out


def _check_dimensions(cat, dims, names):
    """[(lineno, message)] for one section's dimension tuple."""
    errs = []
    for dim in names:
        d = dims.get(dim.casefold())
        if d is None:
            errs.append((0, f"{dim}: missing dimension (### {dim})"))
            continue
        h3_line, body = d
        content = [(n, line) for n, line in body if line.strip()]
        if not content:
            errs.append((h3_line, f"{dim}: empty"))
            continue
        if NA_RE.match(content[0][1]):
            continue
        if dim in NO_POINTER_DIMENSIONS:
            continue
        specs = [(n, SPEC_LINE_RE.match(line).group(1)) for n, line in content
                 if SPEC_LINE_RE.match(line)]
        if not specs:
            errs.append((h3_line, (f"{dim}: no Spec: line -- end it with `Spec: <path>#<anchor>` "
                                  f"or `Spec: none — <reason>`")))
            continue
        nones = [(n, v) for n, v in specs if v.lower().startswith("none")]
        if nones:
            if len(specs) > 1:
                errs.append((nones[0][0], f"{dim}: `Spec: none` must be the only Spec: line"))
            elif not NONE_RE.match(nones[0][1]):
                errs.append((nones[0][0], f"{dim}: `Spec: none` needs a reason after the dash"))
            continue
        for n, v in specs:
            hit, why = resolve_pointer(cat, v)
            if hit is None:
                errs.append((n, f"{dim}: {why}"))
    return errs


def check_story(cat, text):
    """(technical, business). technical is None when the story has no `## Technical acceptance
    criteria` section (pre-provenance). business is None when it has no `## Business acceptance
    criteria` section (pre-business) -- the caller decides whether that is fatal."""
    found, dims = story_dimensions(text)
    technical = _check_dimensions(cat, dims["tac"], DIMENSIONS) if found["tac"] else None
    business = _check_dimensions(cat, dims["bac"], BUSINESS_DIMENSIONS) if found["bac"] else None
    return technical, business


def all_story_files(ctx):
    ctx.need("impl")
    return sorted(glob.glob(os.path.join(ctx.impl, "epic-*", "sprint-*", "stories", "*.md")))


# -- v7 leaves ------------------------------------------------------------------------------ #

# A BMad v7 ticket's frontmatter `type`. A container's acceptance criteria are its children's,
# so only a leaf is checked.
V7_CONTAINER_TYPES = frozenset({"initiative", "epic"})
_FM_TYPE_RE = re.compile(r"""^type:\s*["']?([A-Za-z-]+)""")
# The work types modules.l3io-pm.business_ac_required names (config-resolution.md).
WORK_TYPES = ("CODE", "DOCS", "CONFIG", "MIXED")
BUSINESS_AC_KEY = "modules.l3io-pm.business_ac_required"
BUSINESS_AC_DEFAULT = "CODE,MIXED"


def leaf_type(text):
    """The `type` in a leading YAML frontmatter block, lower-cased, or None."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    for line in lines[1:]:
        if _FM_CLOSE.match(line):
            return None
        m = _FM_TYPE_RE.match(line)
        if m:
            return m.group(1).lower()
    return None


class _PointedCatalog(dict):
    """The catalog of a v7 leaf's own pointer targets. A v7 project's specs are its tickets
    and their sources and companions, which sit beside the ticket tree and under no one
    planning folder, so a pointer's file is looked up where it says it is."""

    missing = "does not exist under the project root"


def pointed_catalog(ctx, texts):
    """Every markdown file under the project root that a `Spec:` line in `texts` names."""
    cat = _PointedCatalog()
    for text in texts:
        for _n, _dim, value in story_pointers(text):
            m = PTR_RE.match(value.strip().strip("`"))
            if not m or m.group(1) in cat or os.path.isabs(m.group(1)):
                continue
            full = os.path.normpath(os.path.join(ctx.project, m.group(1)))
            if _under(full, ctx.project) and os.path.isfile(full):
                cat[m.group(1)] = catalog_entry(ctx, m.group(1), _kind_for_path(full) or "other")
    return cat


def resolve_config_key(ctx, key):
    """One key from BMad core's resolver at `{project-root}/_bmad/scripts/resolve_config.py`,
    or None when the resolver is not installed or does not set the key."""
    script = os.path.join(ctx.project, "_bmad", "scripts", "resolve_config.py")
    if not os.path.isfile(script):
        return None
    runner = (["uv", "run", "--quiet", "--no-project"] if shutil.which("uv")
              else [sys.executable])
    r = subprocess.run([*runner, script, "--project-root", ctx.project, "--key", key],
                       capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise SAError(2, f"{ctx.rel(script)} failed resolving {key}: "
                         f"{(r.stderr or r.stdout).strip()}")
    try:
        return json.loads(r.stdout).get(key)
    except (ValueError, AttributeError):
        raise SAError(2, f"{ctx.rel(script)} printed no JSON object for {key}")


def business_policy(ctx, a):
    """`required` or `advisory` for a v7 leaf of work type `--work-type`. An explicit
    `--business` wins; otherwise the work type is looked up in business_ac_required."""
    if a.business:
        return a.business
    raw = resolve_config_key(ctx, BUSINESS_AC_KEY)
    raw = BUSINESS_AC_DEFAULT if raw is None else raw
    if not isinstance(raw, str):
        raise SAError(2, f"{BUSINESS_AC_KEY} must be a comma-separated string, got {raw!r}")
    types = [t.strip().upper() for t in raw.split(",") if t.strip()]
    bad = [t for t in types if t not in WORK_TYPES]
    if bad:
        raise SAError(2, f"{BUSINESS_AC_KEY} = {raw!r}: {', '.join(bad)} is not a work type; "
                         f"the legal set is {', '.join(WORK_TYPES)}")
    return "required" if (a.work_type or "CODE") in types else "advisory"


