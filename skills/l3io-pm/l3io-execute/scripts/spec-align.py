"""
spec-align.py -- keeps a project's specs and its implementation in step, for l3io-pm.

Subcommands: build, check-pointers, sections, disposition, check-dispositions, adrs,
check-links, lease, migrate-adrs. The 3.x epic-closure spec sync (sync-plan, propose,
commit, reject, check-stale) filed and resolved its items through the issues ledger and went
with it in Task 4.9; Phase 5 re-homes the spec sync beside bmad-retrospective.

It never calls a model. Each spec-alignment point in l3io-execute runs one of these
first, and the result decides whether an agent is dispatched at all.

Global flags come before the subcommand: --project-root (required), --planning-root,
--impl-root, --state-root (default <impl-root>/state), --pm-status, --spec-paths JSON.

On BMad v7, `check-pointers --story-file` checks Sofia's leaf tickets: it needs only
--project-root, resolves each pointer against the markdown file it names under the project
root (unless --planning-root or --spec-paths narrows the catalog), and reads the business-AC
policy from modules.l3io-pm.business_ac_required through BMad core's resolve_config.py. It
writes nothing; it runs inside Sofia's validate checks.

Exit codes: 0 ok; 1 a report-mode check found problems; 2 a gate refused, or bad input;
5 the spec-sync lease is held by another owner.

Design: docs/superpowers/specs/2026-09-11-spec-alignment-design.md in the package repo;
decisions: docs/adr/0004-agents-edit-architecture-specs.md, docs/adr/0005-one-adr-home.md.
"""
